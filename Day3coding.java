public class App {
    public static void main(String[] args) throws Exception {
    
        // (\n) digunakan untuk memindahkan teks ke baris berikutnya
        System.out.println("Hallo!\nPerkenalkan");

        // (\t) digunakan untuk memberikan spasi selebar tab 
        System.out.println("Nama:\tSera");

        // (\") digunakan untuk menambahkan tanda kutip 
        System.out.println("Dia berkata, \"hay!\"");

        // (\\) digunakan untuk backlash
        System.out.println("C:\\Folder\\File.txt");

    }
}
